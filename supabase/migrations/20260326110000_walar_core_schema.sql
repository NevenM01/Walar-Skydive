-- ---------------------------------------------------------------------------
-- Engine: jump stats (SUM N:W â€” rounds 1â€“8 + SF + F)
-- ---------------------------------------------------------------------------
create or replace function public.walar_jump_totals(
  j1 numeric, j2 numeric, j3 numeric, j4 numeric, j5 numeric, j6 numeric, j7 numeric, j8 numeric,
  p_sf numeric, p_f numeric
)
returns table(total_cm numeric, jump_rounds int, avg_cm numeric)
language sql
immutable
parallel safe
as $$
  with vals as (
    select x from unnest(array[j1,j2,j3,j4,j5,j6,j7,j8,p_sf,p_f]) as t(x)
  )
  select
    coalesce((select sum(x)::numeric from vals where x is not null), 0),
    (select count(*)::int from vals where x is not null),
    case
      when (select count(*) from vals where x is not null) > 0
      then (select sum(x)::numeric / count(*)::numeric from vals where x is not null)
      else null
    end;
$$;

-- Rank points (Excel WALARIN column AW)
create or replace function public.walar_rank_points(
  member_national_team boolean,
  age_category text,
  avg_cm numeric,
  wpc_medalist boolean
)
returns numeric
language sql
immutable
parallel safe
as $$
  select
    (case when coalesce(member_national_team, false) then 3 else 1 end)::numeric
    + (case when lower(trim(coalesce(age_category, ''))) = 'junior' then 1 else 0 end)::numeric
    + (case when coalesce(avg_cm, 0) > 10 then -1 else 0 end)::numeric
    + (case when coalesce(wpc_medalist, false) then 2 else 0 end)::numeric;
$$;

-- Results points from PointsCM matrix
create or replace function public.walar_results_points_lookup(p_total_cm numeric, p_jump_rounds int)
returns numeric
language sql
stable
as $$
  select coalesce(
    (
      select w.points
      from public.walar_points_cm w
      where w.total_cm = least(greatest(floor(coalesce(p_total_cm, 0))::int, 0), 160)
        and w.jump_rounds = least(greatest(coalesce(p_jump_rounds, 1), 1), 10)
    ),
    0::numeric
  );
$$;

-- WALAR tier from organizer points (Excel CompetitionsRanking column AB)
create or replace function public.walar_tier_from_op(op numeric)
returns text
language sql
immutable
as $$
  select case
    when op is null then null
    when op > 15000 then 'WALAR A'
    when op > 10000 then 'WALAR B'
    when op > 7500 then 'WALAR C'
    when op > 4000 then 'WALAR D'
    when op > 1500 then 'WALAR E'
    when op > 500 then 'WALAR F'
    else 'Under'
  end;
$$;

-- Recalculate derived points for one result row
create or replace function public.walar_recalculate_competition_result(p_id uuid)
returns void
language plpgsql
as $$
declare
  r public.competition_results%rowtype;
  t numeric;
  jr int;
  a numeric;
  rp numeric;
  rsp numeric;
begin
  select * into r from public.competition_results where id = p_id;
  if not found then
    return;
  end if;
  select jt.total_cm, jt.jump_rounds, jt.avg_cm
  into t, jr, a
  from public.walar_jump_totals(
    r.jump1_cm, r.jump2_cm, r.jump3_cm, r.jump4_cm, r.jump5_cm, r.jump6_cm, r.jump7_cm, r.jump8_cm,
    r.sf_cm, r.f_cm
  ) as jt;
  rp := public.walar_rank_points(r.member_national_team, r.age_category, a, r.wpc_medalist);
  rsp := public.walar_results_points_lookup(t, jr);
  update public.competition_results
  set
    rank_points = rp,
    results_points = rsp,
    wal_ar_score = rp + rsp,
    updated_at = now()
  where id = p_id;
end;
$$;

-- Organizer points: (sum rank_points on comp) replaced by Excel (V+W)*Z*L; MVP uses simplified:
-- OP = (M + F + JM + JF bulletin counts equivalent) * sum(rank_points) * finished_rounds â€” see plan.
-- Here we match structure: competitor_weight_sum * sum_av_rank * rounds (approximation).
-- Full parity requires WALAR sheet COUNTIFS; use bulletin totals when present.
create or replace function public.walar_recalculate_competition_organizer_points(p_competition_id uuid)
returns void
language plpgsql
as $$
declare
  v_finished int;
  v_bulletin_sum int;
  v_sum_rank numeric;
  v_op numeric;
begin
  select c.finished_jump_rounds into v_finished
  from public.competitions c where c.id = p_competition_id;

  select
    coalesce(c.bulletin_male, 0) + coalesce(c.bulletin_female, 0)
    + coalesce(c.bulletin_jm, 0) + coalesce(c.bulletin_jf, 0)
  into v_bulletin_sum
  from public.competitions c where c.id = p_competition_id;

  select coalesce(sum(cr.rank_points), 0) into v_sum_rank
  from public.competition_results cr
  where cr.competition_id = p_competition_id;

  v_finished := greatest(coalesce(v_finished, 0), 0);
  v_bulletin_sum := greatest(coalesce(v_bulletin_sum, 0), 0);

  -- Excel: (V+W)*Z*L where Z is sum of WALAR rating (column AV) â€” we use sum(rank_points) as MVP stand-in until rating column split.
  v_op := v_bulletin_sum::numeric * coalesce(v_sum_rank, 0) * v_finished::numeric;

  update public.competitions
  set
    wal_ar_organizer_points = v_op,
    wal_ar_tier = public.walar_tier_from_op(v_op),
    updated_at = now()
  where id = p_competition_id;
end;
$$;

